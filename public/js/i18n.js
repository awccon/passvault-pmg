  const LANGUAGE_NAMES = { en: 'English', ru: 'Русский' };

  let lang = 'en';

  function t(key, vars) {
    const dict = STRINGS[lang] || STRINGS.en;
    let str = dict[key] !== undefined ? dict[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
    if (vars) {
      Object.keys(vars).forEach(k => { str = str.split('{' + k + '}').join(vars[k]); });
    }
    return str;
  }

  function applyStatic() {
    document.title = t('app.title');
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label'))); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
  }

  function setLanguage(newLang) {
    lang = STRINGS[newLang] ? newLang : 'en';
    try { localStorage.setItem('pv-lang', lang); } catch (e) { /* private browsing, etc. */ }
    document.documentElement.setAttribute('lang', lang);
    applyStatic();
    window.dispatchEvent(new CustomEvent('pv-lang-changed'));
  }

  function init() {
    let saved = 'en';
    try { saved = localStorage.getItem('pv-lang') || 'en'; } catch (e) { /* private browsing, etc. */ }
    lang = STRINGS[saved] ? saved : 'en';
    document.documentElement.setAttribute('lang', lang);
    applyStatic();
  }

  init();

  return {
    t,
    setLanguage,
    getLanguage: () => lang,
    languages: () => Object.keys(STRINGS),
    languageName: (code) => LANGUAGE_NAMES[code] || code
  };
